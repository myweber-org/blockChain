package config

import (
	"errors"
	"os"
	"strconv"
	"strings"
)

type AppConfig struct {
	ServerPort int
	DebugMode  bool
	DatabaseURL string
	CacheTTL   int
}

func LoadConfig() (*AppConfig, error) {
	cfg := &AppConfig{}

	portStr := getEnvWithDefault("APP_PORT", "8080")
	port, err := strconv.Atoi(portStr)
	if err != nil || port < 1 || port > 65535 {
		return nil, errors.New("invalid port configuration")
	}
	cfg.ServerPort = port

	debugStr := getEnvWithDefault("DEBUG_MODE", "false")
	cfg.DebugMode = strings.ToLower(debugStr) == "true"

	dbURL := os.Getenv("DATABASE_URL")
	if dbURL == "" {
		return nil, errors.New("database URL is required")
	}
	cfg.DatabaseURL = dbURL

	ttlStr := getEnvWithDefault("CACHE_TTL", "300")
	ttl, err := strconv.Atoi(ttlStr)
	if err != nil || ttl < 0 {
		return nil, errors.New("invalid cache TTL configuration")
	}
	cfg.CacheTTL = ttl

	return cfg, nil
}

func getEnvWithDefault(key, defaultValue string) string {
	value := os.Getenv(key)
	if value == "" {
		return defaultValue
	}
	return value
}