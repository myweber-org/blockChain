func generateKey() ([]byte, error) {
	key := make([]byte, 32)
	if _, err := rand.Read(key); err != nil {
		return nil, fmt.Errorf("generate key failed: %w", err)
	}
	return key, nil
}

func main() {
	if len(os.Args) < 2 {
		fmt.Println("Usage: file_encryptor <encrypt|decrypt|genkey>")
		os.Exit(1)
	}

	switch os.Args[1] {
	case "encrypt":
		if len(os.Args) != 5 {
			fmt.Println("Usage: file_encryptor encrypt <input> <output> <key_file>")
			os.Exit(1)
		}
		key, err := os.ReadFile(os.Args[4])
		if err != nil {
			fmt.Printf("Read key failed: %v\n", err)
			os.Exit(1)
		}
		if err := encryptFile(os.Args[2], os.Args[3], key); err != nil {
			fmt.Printf("Encryption failed: %v\n", err)
			os.Exit(1)
		}
		fmt.Println("File encrypted successfully")

	case "decrypt":
		if len(os.Args) != 5 {
			fmt.Println("Usage: file_encryptor decrypt <input> <output> <key_file>")
			os.Exit(1)
		}
		key, err := os.ReadFile(os.Args[4])
		if err != nil {
			fmt.Printf("Read key failed: %v\n", err)
			os.Exit(1)
		}
		if err := decryptFile(os.Args[2], os.Args[3], key); err != nil {
			fmt.Printf("Decryption failed: %v\n", err)
			os.Exit(1)
		}
		fmt.Println("File decrypted successfully")

	case "genkey":
		if len(os.Args) != 3 {
			fmt.Println("Usage: file_encryptor genkey <output_key_file>")
			os.Exit(1)
		}
		key, err := generateKey()
		if err != nil {
			fmt.Printf("Generate key failed: %v\n", err)
			os.Exit(1)
		}
		if err := os.WriteFile(os.Args[2], key, 0600); err != nil {
			fmt.Printf("Write key failed: %v\n", err)
			os.Exit(1)
		}
		fmt.Println("Key generated successfully")

	default:
		fmt.Println("Unknown command")
		os.Exit(1)
	}
}